//! fig2dev's experimental `dxf` driver (AutoCAD's Drawing Exchange
//! Format): polylines, polygons and boxes as `POLYLINE`s, arc boxes as
//! four `LINE`s (without corners), circles and ellipses, and texts; the
//! depth is the layer. Arcs and old-style splines only leave comments
//! (and, for splines, HP-GL commands, as fig2dev writes them). Units are
//! inches, or mm for metric figures; y is measured up from the paper's
//! height.
//
// Ported from fig2dev dev/gendxf.c (xfig licence, see LICENSE-xfig).

use super::ibmgl::{cf, ctl_spline, itp_spline, LineStyle, SplineArrow, Tables, PATTERNS};
use crate::gendev::{Ctx, Driver, PAPERDEF};
use crate::object::{
    Arc, Arrow, Compound, Ellipse, Line, Point, Spline, Text, SOLID_LINE, T_ARC_BOX, T_BOX, T_PIC_BOX, T_POLYGON,
    T_POLYLINE,
};
use crate::{fprintf, Out};
use std::f64::consts::PI;

/// The driver for `lang`.
pub fn new(lang: &str) -> Option<Box<dyn Driver>> {
    let _ = lang;
    Some(Box::new(Dxf::default()))
}

