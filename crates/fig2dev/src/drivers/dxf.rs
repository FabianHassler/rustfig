/// C's `%.Ng`.
pub(crate) fn fmt_g(x: f64, prec: usize) -> String {
    if !x.is_finite() {
        return cf(x, 0);
    }
    if x == 0.0 {
        return if x.is_sign_negative() { "-0" } else { "0" }.into();
    }
    let p = prec.max(1);
    let e = format!("{:.*e}", p - 1, x);
    let Some((mant, exp)) = e.split_once('e') else {
        return e;
    };
    let exp: i32 = exp.parse().unwrap_or(0);
    let strip = |s: &str| -> String {
        if s.contains('.') {
            s.trim_end_matches('0').trim_end_matches('.').to_string()
        } else {
            s.to_string()
        }
    };
    if exp < -4 || exp >= p as i32 {
        let sign = if exp < 0 { '-' } else { '+' };
        format!("{}e{}{:02}", strip(mant), sign, exp.unsigned_abs())
    } else {
        let decimals = usize::try_from(p as i32 - 1 - exp).unwrap_or(0);
        strip(&format!("{x:.decimals$}"))
    }
}

/// fig2dev's `static` state of gendxf.c.
#[derive(Debug)]
pub struct Dxf {
    tables: Tables,
    line: LineStyle,
    /// Drawing units (in or mm) per Fig unit.
    figtodxf: f64,
    /// Drawing units per 1/80 inch (line thickness).
    styletodxf: f64,
    /// The paper's height, Fig units.
    paperheight: f64,
}

impl Default for Dxf {
    fn default() -> Dxf {
        Dxf {
            tables: Tables::new(0.6, 0.8),
            line: LineStyle::default(),
            figtodxf: 0.0,
            styletodxf: 0.0,
            paperheight: 0.0,
        }
    }
}

impl Dxf {
    fn set_style(&mut self, out: &mut Out, style: i32, length: f64) {
        let scale = self.styletodxf;
        self.line.set(out, style, length, scale);
    }

    /// `draw_arrow_head`: only a comment.
    fn arrow_head(&mut self, out: &mut Out, x1: f64, y1: f64, x2: f64, y2: f64) {
        let saved = self.line;
        self.set_style(out, SOLID_LINE, 0.0);
        fprintf!(
            out,
            "999\nPrint an arrow from ({};{}) to ({};{})\n",
            cf(x1, 6),
            cf(y1, 6),
            cf(x2, 6),
            cf(y2, 6)
        );
        self.set_style(out, saved.style, saved.dash_length);
    }

    /// `YCOORD(y) * figtodxf`.
    fn ydxf(&self, y: i32) -> f64 {
        (self.paperheight - f64::from(y)) * self.figtodxf
    }

    fn point_entity(&self, out: &mut Out, l: &Line, p: Point) {
        out.puts("  0\nPOINT\n");
        fprintf!(out, "  8\n{:3}\n", l.depth);
        out.puts("  6\nSolid\n");
        fprintf!(out, " 62\n{:6}\n", l.pen_color);
        fprintf!(out, " 10\n{}\n", cf(f64::from(p.x) * self.figtodxf, 6));
        fprintf!(out, " 20\n{}\n", cf(self.ydxf(p.y), 6));
    }
}

impl SplineArrow for Dxf {
    fn spline_arrow(&mut self, out: &mut Out, x1: f64, y1: f64, x2: f64, y2: f64, _a: &Arrow) {
        self.arrow_head(out, x1, y1, x2, y2);
    }
}

fn line_entity(out: &mut Out, l: &Line, x1: f64, y1: f64, x2: f64, y2: f64) {
    out.puts("  0\nLINE\n");
    out.puts("  6\nSolid\n");
    fprintf!(out, "  8\n{:3}\n", l.depth);
    out.puts(" 66\n1\n");
    fprintf!(out, " 62\n{:6}\n", l.pen_color);
    fprintf!(out, " 10\n{}\n", cf(x1, 6));
    fprintf!(out, " 20\n{}\n", cf(y1, 6));
    fprintf!(out, " 11\n{}\n", cf(x2, 6));
    fprintf!(out, " 21\n{}\n", cf(y2, 6));
}

impl Driver for Dxf {
    fn option(&mut self, ctx: &mut Ctx, opt: char, arg: Option<&str>) -> Result<(), String> {
        if self.tables.option(ctx, opt, arg) {
            return Ok(());
        }
        match opt {
            // Accepted and ignored, as in fig2dev.
            'a' | 'c' | 'd' | 'v' | 'G' | 'L' => {}
            'P' => {
                ctx.landscape = false;
                ctx.orientspec = true;
            }
            _ => return Err(format!("Argument -{opt} unknown to dxf driver.")),
        }
        Ok(())
    }

    fn start(&mut self, ctx: &mut Ctx, out: &mut Out, _objects: &Compound) -> Result<(), String> {
        let mag = ctx.mag;
        if mag.abs() < 1.0 / 2048.0 || !mag.is_finite() {
            return Err("|mag| < 1/2048".into());
        }
        if ctx.metric {
            self.figtodxf = mag * 25.4 / ctx.ppi;
            self.styletodxf = mag * 25.4 / 80.0;
        } else {
            self.figtodxf = mag / ctx.ppi;
            self.styletodxf = mag / 80.0;
        }
        // A4 unless the figure's paper size is known.
        let height = PAPERDEF
            .iter()
            .find(|p| p.0.eq_ignore_ascii_case(&ctx.papersize))
            .map_or(842, |p| p.2);
        self.paperheight = f64::from(height) * (ctx.ppi / 72.0);

        out.puts("\t0\nSECTION\n  2\nHEADER\n");
        out.puts("  9\n$INSUNITS\n 70\n");
        // 1: inches, 4: mm.
        out.puts(if ctx.metric { "  4\n" } else { "  1\n" });
        out.puts(TABLES);
        Ok(())
    }

    fn arc(&mut self, _ctx: &mut Ctx, out: &mut Out, _a: &Arc) -> Result<(), String> {
        out.puts("999\n !! found gendxf_arc\n");
        Ok(())
    }

    fn ellipse(&mut self, _ctx: &mut Ctx, out: &mut Out, e: &Ellipse) -> Result<(), String> {
        let k = self.figtodxf;
        if e.radiuses.x == e.radiuses.y {
            out.puts("  0\nCIRCLE\n");
            out.puts("  6\nSolid\n");
            fprintf!(out, "  8\n{:3}\n", e.depth);
            out.puts(" 39\n 1\n");
            fprintf!(out, " 10\n{}\n", fmt_g(f64::from(e.center.x) * k, 4));
            fprintf!(out, " 20\n{}\n", cf(self.ydxf(e.center.y), 4));
            fprintf!(out, " 40\n{}\n", cf(f64::from(e.radiuses.x) * k, 4));
        } else {
            out.puts("  0\nELLIPSE\n");
            out.puts("  6\nSolid\n");
            fprintf!(out, "  8\n{:3}\n", e.depth);
            fprintf!(out, " 10\n{}\n", fmt_g(f64::from(e.center.x) * k, 4));
            fprintf!(out, " 20\n{}\n", cf(self.ydxf(e.center.y), 4));
            // The end of the major axis, relative to the centre.
            fprintf!(out, " 11\n{}\n", cf(f64::from(e.radiuses.x) * k, 4));
            out.puts(" 21\n0.0\n");
            fprintf!(
                out,
                " 40\n {}\n",
                fmt_g(f64::from(e.radiuses.y) / f64::from(e.radiuses.x), 6)
            );
            out.puts(" 41\n0.0\n 42\n6.28318\n");
        }
        Ok(())
    }

    fn line(&mut self, ctx: &mut Ctx, out: &mut Out, l: &Line) -> Result<(), String> {
        if !(l.thickness != 0 || (0 <= l.fill_style && l.fill_style < PATTERNS)) {
            return Ok(());
        }
        self.set_style(out, l.style, l.style_val);
        let k = self.figtodxf;
        let Some(&p) = l.points.first() else {
            return Ok(());
        };
        let q = l.points.get(1).copied();
        match l.type_ {
            T_POLYLINE | T_POLYGON | T_BOX => {
                out.puts(match l.type_ {
                    T_POLYLINE => "999\n !! found polyline\n",
                    T_POLYGON => "999\n !! found polygon\n",
                    _ => "999\n !! found box\n",
                });
                let Some(q) = q else {
                    self.point_entity(out, l, p);
                    return Ok(());
                };
                if l.thickness != 0 {
                    if let Some(_a) = &l.back_arrow {
                        let (x1, y1) = (f64::from(q.x) * k, self.ydxf(q.y));
                        let (x2, y2) = (f64::from(p.x) * k, self.ydxf(p.y));
                        self.arrow_head(out, x1, y1, x2, y2);
                    }
                }
                out.puts("  0\nPOLYLINE\n");
                out.puts("  6\nSolid\n");
                fprintf!(out, "  8\n{:3}\n", l.depth);
                out.puts(" 66\n1\n");
                fprintf!(out, " 62\n{:6}\n", l.pen_color);
                out.puts(" 10\n0.0\n 20\n0.0\n 30\n0.0\n");
                out.puts(if l.type_ == T_POLYLINE {
                    " 70\n  0\n"
                } else {
                    " 70\n  1\n"
                });
                for v in &l.points {
                    out.puts("  0\nVERTEX\n");
                    fprintf!(out, "  8\n{:3}\n", l.depth);
                    out.puts("  6\nSolid\n");
                    fprintf!(out, " 10\n{}\n", cf(f64::from(v.x) * k, 6));
                    fprintf!(out, " 20\n{}\n", cf(self.ydxf(v.y), 6));
                    out.puts(" 30\n0.0\n");
                    out.puts(" 70\n  0\n");
                }
                let n = l.points.len();
                if let (true, Some(_a), Some(&r), Some(&q)) =
                    (l.thickness != 0, &l.for_arrow, l.points.get(n - 2), l.points.get(n - 1))
                {
                    let (x1, y1) = (f64::from(r.x) * k, self.ydxf(r.y));
                    let (x2, y2) = (f64::from(q.x) * k, self.ydxf(q.y));
                    self.arrow_head(out, x1, y1, x2, y2);
                }
                out.puts("  0\nSEQEND\n");
            }
            T_ARC_BOX => {
                // YCOORD truncated to int, compared with raw y, as in C.
                let yc = |y: i32| (self.paperheight - f64::from(y)) as i32;
                let (mut llx, mut urx) = (p.x, p.x);
                let (mut lly, mut ury) = (yc(p.y), yc(p.y));
                for r in l.points.iter().skip(1) {
                    if llx > r.x {
                        llx = r.x;
                    }
                    if urx < r.x {
                        urx = r.x;
                    }
                    if lly > r.y {
                        lly = yc(r.y);
                    }
                    if ury < r.y {
                        ury = yc(r.y);
                    }
                }
                let (x0, x1) = (f64::from(llx) * k, f64::from(urx) * k);
                let dx = f64::from(l.radius) * k;
                let (y0, y1) = (f64::from(ury) * k, f64::from(lly) * k);
                let dy = -dx;
                out.puts("999\n !! found arc-box\n");
                if q.is_none() {
                    // fig2dev dereferences a null pointer here.
                    self.point_entity(out, l, p);
                } else {
                    line_entity(out, l, x0, y0 + dy, x0, y1 - dy);
                    line_entity(out, l, x1, y0 + dy, x1, y1 - dy);
                    line_entity(out, l, x0 + dx, y0, x1 - dx, y0);
                    line_entity(out, l, x0 + dx, y1, x1 - dx, y1);
                }
            }
            T_PIC_BOX => ctx.warn("Warning: Pictures not supported in IBMGL language"),
            _ => {}
        }
        Ok(())
    }

    fn spline(&mut self, ctx: &mut Ctx, out: &mut Out, s: &Spline) -> Result<(), String> {
        out.puts("999\n !! found spline FIX \n");
        if s.thickness != 0 {
            self.set_style(out, s.style, s.style_val);
            let k = self.figtodxf;
            let sc = move |v: f64| v * k;
            if s.int_spline() {
                itp_spline(self, out, s, &sc, &sc);
            } else {
                ctl_spline(self, out, s, &sc, &sc);
            }
        }
        if 0 < s.fill_style && s.fill_style < PATTERNS {
            ctx.warn("Spline area fill not implemented");
        }
        Ok(())
    }

    fn text(&mut self, _ctx: &mut Ctx, out: &mut Out, t: &Text) -> Result<(), String> {
        let bytes = t.raw.clone();
        out.puts("999\n !! found text ");
        out.bytes(&bytes);
        out.puts("\n");
        let font = Tables::font(t.font);
        let k = self.figtodxf;
        out.puts("  0\nTEXT\n");
        fprintf!(out, "  8\n{:3}\n", t.depth);
        out.puts("  6\nSolid\n");
        fprintf!(out, " 62\n{:6}\n", t.color);
        let x = cf(f64::from(t.base_x) * k, 6);
        let y = cf(self.ydxf(t.base_y), 6);
        fprintf!(out, " 10\n{}\n", x);
        fprintf!(out, " 11\n{}\n", x);
        fprintf!(out, " 20\n{}\n", y);
        fprintf!(out, " 21\n{}\n", y);
        fprintf!(out, " 50\n{}\n", cf(180.0 / PI * t.angle, 6));
        fprintf!(out, " 72\n{:3}\n", t.type_);
        // fig2dev keeps the size in an int.
        let size = f64::from(t.size as i32);
        let height = size * self.tables.high.get(font).copied().unwrap_or(0.0);
        fprintf!(out, " 40\n{}\n", cf(height, 6));
        out.puts("  1\n");
        out.bytes(&bytes);
        out.puts("\n");
        Ok(())
    }

    fn end(&mut self, _ctx: &mut Ctx, out: &mut Out) -> Result<i32, String> {
        out.puts("  0\nENDSEC\n");
        out.puts("  0\nEOF\n");
        Ok(0)
    }

    fn text_include(&self) -> bool {
        false
    }
}
