#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_pattern_has_all_its_bytes() {
        for p in TKPATTERN {
            assert_eq!(p.bits.len(), p.width.div_ceil(8) * p.height, "{}", p.name);
        }
    }
}
