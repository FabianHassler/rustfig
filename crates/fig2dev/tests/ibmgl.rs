fn ibmgl(opts: &[(char, Option<&str>)]) -> Result<(String, Vec<String>, i32), String> {
    run_with("ibmgl", FIG.as_bytes(), None, opts, false)
}

#[test]
fn polyline_arrow_box_circle_text() {
    let (out, msgs, exit) = ibmgl(&[]).unwrap();
    assert_eq!(out, IBMGL);
    assert!(msgs.is_empty(), "{msgs:?}");
    assert_eq!(exit, 0);
}

#[test]
fn without_cartridge_and_with_pcl() {
    let (out, _, _) = ibmgl(&[('c', None), ('k', None)]).unwrap();
    assert_eq!(out, IBMGLCK);
}

#[test]
fn errors() {
    assert_eq!(
        ibmgl(&[('q', None)]).unwrap_err(),
        "Argument -q unknown to ibmgl driver."
    );
    assert_eq!(ibmgl(&[('d', Some("5,1,2,6"))]).unwrap_err(), "xur <= xll");
    let (_, msgs, _) = ibmgl(&[('p', Some("/nonexistent/pens"))]).unwrap();
    assert_eq!(msgs, ["Couldn't open /nonexistent/pens"]);
}

/// Opt-in: `cargo test -p rustfig-fig2dev --test ibmgl -- --ignored --nocapture`.
#[test]
#[ignore]
fn same_as_fig2dev() {
    let opts: &[&[&str]] = &[
        &[],
        &["-c"],
        &["-F"],
        &["-k", "-v"],
        &["-P", "-a"],
        &["-z", "A3", "-S", "20", "-x", "1", "-y", "1"],
        &["-d", "1,1,8,6", "-m", "0.5"],
    ];
    if let Some((same, total)) = compare_with_fig2dev("ibmgl", &HAND, opts) {
        assert!(same * 10 >= total * 9, "{same} of {total} identical");
    }
}
