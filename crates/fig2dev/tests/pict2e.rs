#[test]
fn options_and_messages() {
    let body = "2 1 0 1 0 7 50 -1 -1 0.000 0 0 -1 0 0 2\n\t 600 600 1800 900\n";
    let (_, msgs, _) = run("pict2e", body, &[('f', Some("nope"))]).unwrap();
    assert_eq!(msgs, ["warning: non-standard font name nope ignored"]);
    let err = run("pict2e", body, &[('q', Some("1"))]).unwrap_err();
    assert_eq!(err, "Argument -q unknown to pict2e driver.");
    // -G is accepted and ignored (fig2dev's test "ignore -G option").
    let (out, _, exit) = run("pict2e", body, &[('G', Some("0.2:1cm"))]).unwrap();
    assert_eq!(exit, 0);
    assert!(out.contains("\\Line(12,312)(1212,12)"), "{out}");
    let spline = "3 0 0 1 0 7 50 -1 -1 0.000 0 0 0 3\n\t 600 600 1200 1200 1800 600\n";
    let fig = format!("#FIG 3.1\nLandscape\nCenter\nInches\n1200 2\n{spline}");
    let (_, msgs, _) = tex_common::run_with("pict2e", fig.as_bytes(), None, &[], false).unwrap();
    assert!(
        msgs.contains(&"Can't generate spline; omitting object".to_string()),
        "{msgs:?}"
    );
}

