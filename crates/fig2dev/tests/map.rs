#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
//! fig2dev's `map` driver against output of the real fig2dev 3.2.9a.

mod mp_common;
mod tex_common;

const BODY: &str = concat!(
    "# HREF=\"http://a\" ALT=\"A\"\n",
    "2 1 1 2 4 7 50 -1 -1 4.000 0 0 -1 1 0 3\n",
    "\t1 1 1.00 60.00 120.00\n",
    "\t 600 600 1800 600 1800 1200\n",
    "1 3 0 1 0 7 40 -1 20 0.000 1 0.0000 1200 2400 300 300 1200 2400 1500 2400\n",
    "4 1 0 30 -1 0 12 0.0000 4 135 450 2400 2400 a_b\\001\n",
);

const EXPECTED: &str = concat!(
    "<!DOCTYPE HTML PUBLIC \"-//W3C//DTD HTML 4.0 Frameset//EN\">\n",
    "<HTML>\n",
    "<HEAD><TITLE>HTML imagemap generated by fig2dev</TITLE></HEAD>\n",
    "<BODY>\n",
    "\n",
    "<H1>HTML imagemap generated by fig2dev</H1>\n",
    "<P>This file is generated by fig2dev.</P>\n",
    "<P>You can copy the following lines into your HTML document.\n",
    "You may need to edit the name of the image file in the first line.</P>\n",
    "\n",
    "<IMG SRC=\"imagemap.png\" USEMAP=\"#imagemap\">\n",
    "<MAP NAME=\"imagemap\">\n",
    "<AREA SHAPE=\"poly\" COORDS=\"1,1,81,1,81,41\" HREF=\"http://a\" ALT=\"A\">\n",
    "</MAP>\n",
    "\n",
    "<h2>Alternative Text Links</h2>\n",
    "<P>Because not all people can use imagemaps,\n",
    "it is recommended to prepare an alternative way for the people\n",
    "who can't use or don't want to use them.</P>\n",
    "<P>Here are text the links extracted from the above imagemap.\n",
    "If the ALT attribute (it is required in HTML 3.2) was not specified\n",
    "in the imagemap, those URLs will be displayed\n",
    "instead of labels specified by the ALT attributes.</P>\n",
    "\n",
    "<P ALIGN=\"CENTER\">\n",
    "<A HREF=\"http://a\">A</A>\n",
    "</P>\n",
    "\n",
    "</BODY>\n",
    "</HTML>\n",
);

#[test]
fn as_fig2dev() {
    let (out, msgs) = mp_common::run("map", BODY, &[]);
    assert_eq!(out, EXPECTED);
    assert!(msgs.is_empty(), "{msgs:?}");
}

#[test]
fn unknown_option() {
    let mut d = rustfig_fig2dev::drivers::driver("map").unwrap();
    let mut ctx = rustfig_fig2dev::Ctx::default();
    assert_eq!(
        d.option(&mut ctx, 'q', None).unwrap_err(),
        "Argument -q unknown to map driver."
    );
    assert!(d.option(&mut ctx, 'G', Some("1")).is_ok());
}

#[test]
fn border_and_magnification() {
    let (out, _) = mp_common::run("map", BODY, &[('b', Some("5")), ('m', Some("2"))]);
    assert!(
        out.contains("<AREA SHAPE=\"poly\" COORDS=\"8,8,168,8,168,88\" HREF=\"http://a\" ALT=\"A\">\n"),
        "{out}"
    );
}

/// Opt-in: `cargo test -p rustfig-fig2dev --test map -- --ignored --nocapture`.
#[test]
#[ignore]
fn same_as_fig2dev() {
    if let Some((same, total)) = mp_common::compare(
        "map",
        &mp_common::HAND,
        &[&[], &[('b', Some("5"))], &[('m', Some("0.5"))]],
    ) {
        assert!(same * 10 >= total * 9, "{same} of {total} identical");
    }
}
