fn dxf(fig: &str, opts: &[(char, Option<&str>)]) -> Result<(String, Vec<String>, i32), String> {
    run_with("dxf", fig.as_bytes(), None, opts, false)
}

#[test]
fn polyline_arrow_box_circle_text() {
    let (out, msgs, exit) = dxf(FIG, &[]).unwrap();
    assert_eq!(out, DXF);
    assert!(msgs.is_empty(), "{msgs:?}");
    assert_eq!(exit, 0);
    // -P and the ignored options change nothing here.
    let (out, _, _) = dxf(FIG, &[('P', None), ('a', None), ('d', Some("x"))]).unwrap();
    assert_eq!(out, DXF);
}

#[test]
fn metric_units_and_errors() {
    let (out, _, _) = dxf(&FIG.replace("Inches", "Metric"), &[]).unwrap();
    assert!(out.starts_with("\t0\nSECTION\n  2\nHEADER\n  9\n$INSUNITS\n 70\n  4\n"));
    assert_eq!(
        dxf(FIG, &[('q', None)]).unwrap_err(),
        "Argument -q unknown to dxf driver."
    );
}

/// Opt-in: `cargo test -p rustfig-fig2dev --test dxf -- --ignored --nocapture`.
#[test]
#[ignore]
fn same_as_fig2dev() {
    let opts: &[&[&str]] = &[&[], &["-P", "-m", "2"]];
    if let Some((same, total)) = compare_with_fig2dev("dxf", &HAND, opts) {
        assert!(same * 10 >= total * 9, "{same} of {total} identical");
    }
}
