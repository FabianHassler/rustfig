#[test]
fn table_accuracy() {
    let mut worst: std::collections::BTreeMap<String, (f64, String)> = Default::default();
    for &(name, n, x, want) in TABLE {
        let got = call(name, n, x);
        // Relative error, except where an oscillating function is tiny next
        // to its scale (near zeros of J and Y): absolute error then.
        let osc = matches!(name, "jn" | "yn" | "j0" | "j1" | "y0" | "y1");
        let e = if (osc && want.abs() < 1e-3) || want == 0.0 {
            (got - want).abs() * 1e3
        } else {
            (got - want).abs() / want.abs()
        };
        let w = worst.entry(name.to_string()).or_insert((0.0, String::new()));
        if e.is_nan() || e > w.0 {
            let e = if e.is_nan() { f64::INFINITY } else { e };
            *w = (e, format!("{name}({n},{x}) = {got:e}, want {want:e}"));
        }
    }
    let mut bad = Vec::new();
    for (name, (e, at)) in &worst {
        eprintln!("{name:10} worst {e:.2e}  {at}");
        let tol = if name == "lgamma" { 5e-10 } else { 1e-9 };
        if *e > tol {
            bad.push(format!("{name}: {e:e} at {at}"));
        }
    }
    assert!(bad.is_empty(), "{bad:#?}");
}

fn close(got: f64, want: f64, tol: f64) {
    assert!(
        (got - want).abs() <= tol * want.abs().max(1e-300),
        "got {got:e}, want {want:e}"
    );
}

#[test]
fn well_known_values() {
    let pi = std::f64::consts::PI;
    close(call("j0", f64::NAN, 1.0), 0.7651976865579666, 1e-13);
    close(call("j1", f64::NAN, 1.0), 0.4400505857449335, 1e-13);
    close(call("y0", f64::NAN, 1.0), 0.08825696421567696, 1e-13);
    close(call("y1", f64::NAN, 1.0), -0.7812128213002887, 1e-13);
    close(call("i0", f64::NAN, 1.0), 1.2660658777520082, 1e-13);
    close(call("i1", f64::NAN, 1.0), 0.5651591039924851, 1e-13);
    close(call("k0", f64::NAN, 1.0), 0.42102443824070834, 1e-13);
    close(call("k1", f64::NAN, 1.0), 0.6019072301972346, 1e-13);
    close(call("gamma", f64::NAN, 0.5), pi.sqrt(), 1e-13);
    close(call("gamma", f64::NAN, 5.0), 24.0, 1e-15);
    close(call("lgamma", f64::NAN, 10.0), 12.801827480081469, 1e-13);
    close(call("erf", f64::NAN, 1.0), 0.8427007929497149, 1e-13);
    close(call("erfc", f64::NAN, 3.0), 2.209049699858544e-5, 1e-12);
    close(call("jn", 5.0, 10.0), -0.23406152818679364, 1e-12);
    close(call("jn", 5.2, 10.0), -0.23406152818679364, 1e-12); // n rounds
    close(call("jn", -1.0, 1.0), -0.4400505857449335, 1e-13);
    close(call("j0", f64::NAN, 100.0), 0.019985850304223122, 1e-11);
    close(call("i0", f64::NAN, 10.0), 2815.716628466254, 1e-13);
    close(call("in", 2.0, 1.0), 0.13574766976703828, 1e-13);
    close(call("kn", 2.0, 1.0), 1.6248388986351774, 1e-13);
    close(call("yn", 2.0, 1.0), -1.6506826068162546, 1e-13);
    close(call("gamma", f64::NAN, -1.5), 4.0 * pi.sqrt() / 3.0, 1e-13);
    assert_eq!(call("heaviside", f64::NAN, -2.0), 0.0);
    assert_eq!(call("heaviside", f64::NAN, 2.0), 1.0);
    assert_eq!(call("heaviside", f64::NAN, 0.0), 0.5);
    assert!(call("heaviside", f64::NAN, f64::NAN).is_nan());
}

#[test]
fn domains() {
    for f in ["y0", "y1", "k0", "k1"] {
        assert!(call(f, f64::NAN, -1.0).is_nan(), "{f}(-1)");
    }
    assert!(call("yn", 3.0, -1.0).is_nan());
    assert!(call("kn", 3.0, -1.0).is_nan());
    assert!(call("gamma", f64::NAN, 0.0).is_nan());
    assert!(call("gamma", f64::NAN, -3.0).is_nan());
    assert!(call("jn", 1001.0, 1.0).is_nan());
    assert!(call("jn", f64::NAN, 1.0).is_nan());
    assert!(!call("jn", 1000.0, 1.0).is_nan());
    assert!(call("k0", f64::NAN, 0.0).is_infinite());
}

#[test]
fn wronskians() {
    let pi = std::f64::consts::PI;
    for i in 1..400 {
        let x = f64::from(i) * 0.37;
        let (j0, j1) = (call("j0", f64::NAN, x), call("j1", f64::NAN, x));
        let (y0, y1) = (call("y0", f64::NAN, x), call("y1", f64::NAN, x));
        assert!(
            (j1 * y0 - j0 * y1 - 2.0 / (pi * x)).abs() < 1e-11 / x.sqrt(),
            "JY at {x}"
        );
        if x < 600.0 {
            let (i0, i1) = (call("i0", f64::NAN, x), call("i1", f64::NAN, x));
            let (k0, k1) = (call("k0", f64::NAN, x), call("k1", f64::NAN, x));
            let w = i0 * k1 + i1 * k0;
            assert!((w * x - 1.0).abs() < 1e-12, "IK at {x}: {}", w * x);
        }
    }
}

#[test]
fn hostile_inputs_never_panic() {
    let xs = [
        f64::NAN,
        f64::INFINITY,
        f64::NEG_INFINITY,
        1e300,
        -1e300,
        0.0,
        -0.0,
        1e-300,
        5e-324,
        1e5,
        -1e5,
    ];
    for f in [
        "j0",
        "j1",
        "y0",
        "y1",
        "i0",
        "i1",
        "k0",
        "k1",
        "gamma",
        "lgamma",
        "erf",
        "erfc",
        "heaviside",
    ] {
        for &x in &xs {
            let _ = call(f, f64::NAN, x);
        }
    }
    let ns = [
        0.0,
        1.0,
        -3.0,
        7.0,
        999.0,
        1000.0,
        1001.0,
        f64::NAN,
        f64::INFINITY,
        1e300,
    ];
    for f in ["jn", "yn", "in", "kn"] {
        for &n in &ns {
            for &x in &xs {
                let _ = call(f, n, x);
            }
        }
    }
    // Limits that have a natural value.
    assert_eq!(call("erf", f64::NAN, f64::INFINITY), 1.0);
    assert_eq!(call("erfc", f64::NAN, f64::INFINITY), 0.0);
    assert_eq!(call("erfc", f64::NAN, f64::NEG_INFINITY), 2.0);
    assert_eq!(call("j0", f64::NAN, f64::INFINITY), 0.0);
}

