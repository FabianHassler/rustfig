//! xfig's mode panel icons: the 36×36 ("big", xfig's default) XBM bitmaps
//! from xfig's `src/w_icons.c`, copied verbatim (xfig licence, see
//! LICENSE-xfig). Bits are XBM: rows padded to whole bytes, least
//! significant bit leftmost.

/// A monochrome bitmap.
pub struct Xbm {
    pub name: &'static str,
    pub width: usize,
    pub height: usize,
    pub bits: &'static [u8],
}

/// Paint `icon` centred in `rect`, one bitmap pixel per point, tinted
/// (the texture is white where the bitmap is set; made once per icon and
/// kept in egui's memory).
pub fn paint(ui: &egui::Ui, icon: &'static Xbm, rect: egui::Rect, tint: egui::Color32) {
    let id = egui::Id::new(("xfig-icon", icon.name));
    let cached: Option<egui::TextureHandle> = ui.ctx().data(|d| d.get_temp(id));
    let tex = cached.unwrap_or_else(|| {
        let mut img = egui::ColorImage::filled([icon.width, icon.height], egui::Color32::TRANSPARENT);
        for y in 0..icon.height {
            for x in 0..icon.width {
                if icon.get(x, y) {
                    if let Some(px) = img.pixels.get_mut(y * icon.width + x) {
                        *px = egui::Color32::WHITE;
                    }
                }
            }
        }
        let t = ui
            .ctx()
            .load_texture(format!("xfig-icon-{}", icon.name), img, egui::TextureOptions::NEAREST);
        ui.ctx().data_mut(|d| d.insert_temp(id, t.clone()));
        t
    });
    let r = egui::Rect::from_center_size(rect.center(), egui::vec2(icon.width as f32, icon.height as f32));
    ui.painter().with_clip_rect(rect).image(
        tex.id(),
        r,
        egui::Rect::from_min_max(egui::pos2(0.0, 0.0), egui::pos2(1.0, 1.0)),
        tint,
    );
}

impl Xbm {
    /// Whether the pixel at (x, y) is set.
    pub fn get(&self, x: usize, y: usize) -> bool {
        let stride = self.width.div_ceil(8);
        self.bits
            .get(y * stride + x / 8)
            .is_some_and(|b| b & (1 << (x % 8)) != 0)
    }
}

